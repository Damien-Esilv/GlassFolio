/** Current period of a quest: its key (a new key starts the quest over) and its bounds */
function questPeriod(frequency: GamificationQuest['frequency'], now: Date): { key: string; start: Date; end: Date } {
    const year = now.getFullYear();
    if (frequency === 'quarterly') {
        const quarter = Math.floor(now.getMonth() / 3);
        return { key: `${year}-Q${quarter + 1}`, start: new Date(year, quarter * 3, 1), end: new Date(year, quarter * 3 + 3, 1) };
    }
    if (frequency === 'onboarding') {
        return { key: 'onboarding', start: new Date(0), end: new Date(8.64e15) };
    }
    const month = now.getMonth();
    return { key: `${year}-${String(month + 1).padStart(2, '0')}`, start: new Date(year, month, 1), end: new Date(year, month + 1, 1) };
}

/** Progress measured from the user's own data during the period */
function measureQuest(id: string, start: Date, end: Date, stored: GamificationQuest | undefined): number {
    switch (id) {
        case 'quest_dca_habit':
            // Buys and deposits the user made (not rows generated by a reconciliation)
            return db.getUnifiedTransactions().filter(tx => {
                if (tx.isSynthetic || (tx.type !== 'BUY' && tx.type !== 'DEPOSIT')) return false;
                const at = new Date(tx.transactionDate).getTime();
                return at >= start.getTime() && at < end.getTime();
            }).length;
        case 'quest_allocation_audit':
            return new Set(db.getPositions()
                .filter(p => p.quantity > 0 && p.type !== 'Cash')
                .map(p => p.type)).size;
        default:
            // Visits are recorded as they happen (recordDashboardVisit)
            return stored?.progress ?? 0;
    }
}

/**
 * Quests of the current periods, measured on the data. A quest claimed in an earlier period starts
 * over; one completed and claimed in this period stays claimed.
 */
function computeQuests(now: Date = new Date()): { quests: GamificationQuest[]; changed: boolean } {
    const storedById = new Map(db.getQuests().map(q => [q.id, q]));
    let changed = storedById.size !== QUEST_DEFINITIONS.length;
    const quests = QUEST_DEFINITIONS.map(definition => {
        const period = questPeriod(definition.frequency, now);
        const previous = storedById.get(definition.id);
        const samePeriod = previous?.periodKey === period.key;
        const stored = samePeriod ? previous : undefined;
        const progress = Math.min(definition.target, measureQuest(definition.id, period.start, period.end, stored));
        const quest: GamificationQuest = {
            ...definition,
            progress,
            completed: stored?.claimed === true || progress >= definition.target,
            claimed: stored?.claimed === true,
            periodKey: period.key,
            expiryDate: new Date(period.end.getTime() - 1).toISOString(),
        };
        if (!previous || previous.progress !== quest.progress || previous.completed !== quest.completed
            || previous.claimed !== quest.claimed || previous.periodKey !== quest.periodKey) {
            changed = true;
        }
        return quest;
    });
    return { quests, changed };
}

/** Saves only an actual change: reading quests must not write (the vault may be closing) */
function persistQuests(quests: GamificationQuest[]): void {
    try {
        db.saveQuests(quests);
    } catch (err) {
        console.warn('[gamification] Quests not saved', err);
    }
}

export const gamificationService = {
    /**
     * Returns the user's investor rank based on current level.
     */
    getInvestorRank: (level: number): InvestorRank => {
        const found = INVESTOR_RANKS.find(r => level >= r.levelMin && level <= r.levelMax);
        return found || INVESTOR_RANKS[0];
    },

    /**
     * Calculates the level given total XP. Formula: floor(sqrt(xp / 100)) + 1
     */
    calculateLevel: (xp: number): number => {
        return Math.floor(Math.sqrt((xp || 0) / 100)) + 1;
    },

    /**
     * Calculates total XP required to reach a specific level.
     */
    calculateXpForLevel: (level: number): number => {
        if (level <= 1) return 0;
        return Math.pow(level - 1, 2) * 100;
    },

    /**
     * Returns progress details within the current level:
     * - currentLevelXp: XP accumulated in this level
     * - neededLevelXp: Total XP required to pass to next level
     * - progressPercent: 0 to 100
     */
    calculateLevelProgress: (xp: number) => {
        const currentLevel = Math.floor(Math.sqrt((xp || 0) / 100)) + 1;
        const currentLevelBaseXp = Math.pow(currentLevel - 1, 2) * 100;
        const nextLevelBaseXp = Math.pow(currentLevel, 2) * 100;
        const levelRange = nextLevelBaseXp - currentLevelBaseXp;
        const xpInCurrentLevel = Math.max(0, (xp || 0) - currentLevelBaseXp);
        const progressPercent = Math.min(100, Math.round((xpInCurrentLevel / levelRange) * 100));

        return {
            level: currentLevel,
            currentLevelBaseXp,
            nextLevelBaseXp,
            xpInCurrentLevel,
            levelRange,
            progressPercent
        };
    },

    /**
     * Returns all unlockable theme rewards with unlocked status evaluated against level.
     */
    getThemeRewards: async (userLevel: number): Promise<ThemeReward[]> => {
        await delay(150);
        return THEME_REWARDS.map(theme => ({
            ...theme,
            unlocked: userLevel >= theme.requiredLevel
        }));
    },

    /**
     * Quests of the current periods, with their progress measured on the user's data.
     */
    getQuests: async (): Promise<GamificationQuest[]> => {
        await delay(200);
        const { quests, changed } = computeQuests();
        if (changed) persistQuests(quests);
        return quests;
    },

    /** The monthly review quest: the dashboard was opened this month */
    recordDashboardVisit: async (): Promise<void> => {
        const { quests } = computeQuests();
        const review = quests.find(q => q.id === 'quest_monthly_review');
        if (!review || review.progress >= review.target) return;
        persistQuests(quests.map(q => q.id === review.id
            ? { ...q, progress: q.target, completed: true }
            : q));
    },

    /** Every dated gain of experience points, oldest first. */
    getXpEvents: async (): Promise<XpEvent[]> => {
        await delay(100);
        return db.getXpEvents();
    },

    /**
     * Records a gain of experience points with its date, so that "XP earned this week" can be told.
     * Returns the stored event, or null for a gain of nothing.
     */
    recordXp: async (amount: number, source: XpEvent['source'], refId?: string, at: Date = new Date()): Promise<XpEvent | null> => {
        await delay(50);
        if (!Number.isFinite(amount) || amount <= 0) return null;
        const event: XpEvent = {
            id: `xp-${at.getTime()}-${Math.random().toString(36).slice(2, 9)}`,
            date: at.toISOString(),
            amount: Math.round(amount),
            source,
            refId
        };
        db.saveXpEvents([...db.getXpEvents(), event]);
        return event;
    },

    /**
     * Claims reward for a completed quest and persists its claimed status.
     */
    claimQuestReward: async (questId: string): Promise<{ success: boolean; xpReward: number }> => {
        await delay(200);
        const { quests } = computeQuests();
        const quest = quests.find(q => q.id === questId);
        if (!quest || !quest.completed || quest.claimed) {
            return { success: false, xpReward: 0 };
        }
        db.saveQuests(quests.map(q => q.id === questId ? { ...q, claimed: true } : q));
        return { success: true, xpReward: quest.rewardXp };
    },

    /**
     * Gets pinned badge IDs (max 3).
     */
    getPinnedBadges: async (): Promise<string[]> => {
        await delay(100);
        return db.getPinnedBadges();
    },

    /**
     * Saves pinned badge IDs.
     */
    setPinnedBadges: async (badgeIds: string[]): Promise<string[]> => {
        await delay(100);
        const trimmed = badgeIds.slice(0, 3);
        db.savePinnedBadges(trimmed);
        return trimmed;
    }
};
